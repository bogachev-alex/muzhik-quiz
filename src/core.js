function userDom(A) {
  let base = 50, shift = -4; // -4 компенсирует средний сдвиг остальных ответов
  for (const q of QUESTIONS) {
    if (q.slider) continue;
    const o = q.opts.find(x => x[0] === A[q.id]); if (!o) continue;
    if (o[4].y != null) base = o[4].y;
    if (o[4].dom) shift += o[4].dom;
  }
  return Math.max(3, Math.min(97, Math.round(base + shift)));
}

/** Балл совпадения аромата p с ответами A. Возвращает { s, parts } для блока «почему именно он». */
function scoreFor(p, A, ydom) {
  let s = p.bias; const parts = [];
  for (const q of QUESTIONS) {
    if (q.slider) continue;
    const o = q.opts.find(x => x[0] === A[q.id]); if (!o) continue;
    const w = o[4], qw = q.w || 1;
    let c = 0; const hit = [];
    for (const k of TAGS) if (w[k]) { const v = w[k] * p.tn[k]; c += v; if (v > 0) hit.push([k, v]); }
    if (w.formal) c += w.formal * (p.formal - .5) * 2;
    if (w.loud) c += w.loud * (p.loud - 2) * .7;
    c *= qw; s += c;
    if (q.id === 'age') { s += 1.6 - Math.abs(o[5] - p.age) / 7; continue; }
    parts.push({ label: o[2], c, hit: hit.sort((a,b)=>b[1]-a[1]).map(h=>h[0]) });
  }
  s += 2.4 - Math.abs((A.rug ?? 50) - p.rug) / 16;
  s += 2.2 - Math.abs((ydom ?? userDom(A)) - p.dom) / 16;
  return { s, parts };
}
